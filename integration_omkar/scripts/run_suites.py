def run_suite_integration_unit() -> SuiteResult:
    env_aiml = os.environ.copy()
    env_aiml["PYTHONPATH"] = f"{BASE_DIR}:{os.path.join(BASE_DIR, 'aiml_hemalatha')}:{os.path.join(BASE_DIR, 'integration_omkar', 'docker', 'shim')}"
