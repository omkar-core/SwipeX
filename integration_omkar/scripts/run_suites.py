BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

class SuiteResult:
    def __init__(self, name: str):
        self.name = name
        self.passed = 0
        self.failed = 0  # Includes failures and errors
        self.skipped = 0
        self.blocked = 0
        self.duration = 0.0
        self.exit_code = 0
        self.message = ""

def parse_junit_xml(xml_path: str) -> tuple[int, int, int]:
    """
    Parses JUnit XML generated by pytest --junitxml.
    Returns (passed, failed_with_errors, skipped).
    Errors are strictly counted as failed.
    """
    if not os.path.exists(xml_path) or os.path.getsize(xml_path) == 0:
        return 0, 0, 0

    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()
    except Exception:
        return 0, 0, 0

    total_tests = 0
    total_failures = 0
    total_errors = 0
    total_skipped = 0

    suite_nodes = []
    if root.tag == "testsuite":
        suite_nodes.append(root)
    elif root.tag == "testsuites":
        suite_nodes.extend(root.findall("testsuite"))
    else:
        suite_nodes = root.findall(".//testsuite")
        if not suite_nodes:
            suite_nodes = [root]

    for s in suite_nodes:
        total_tests += int(s.attrib.get("tests", 0))
        total_failures += int(s.attrib.get("failures", 0))
        total_errors += int(s.attrib.get("errors", 0))
        total_skipped += int(s.attrib.get("skipped", 0))

    failed = total_failures + total_errors
    passed = max(0, total_tests - (failed + total_skipped))
    return passed, failed, total_skipped

def parse_pytest_output(stdout: str) -> tuple[int, int, int]:
    """
    Fallback regex parser for pytest console summary.
    Errors are strictly counted as failed.
    """
    passed = 0
    failed = 0
    errors = 0
    skipped = 0

    match = re.search(r"==+ (.*?) in \d+\.?\d*s ==", stdout)
    summary_text = match.group(1) if match else stdout

    pass_match = re.search(r"(\d+)\s+passed", summary_text)
    if pass_match:
        passed = int(pass_match.group(1))
    fail_match = re.search(r"(\d+)\s+failed", summary_text)
    if fail_match:
        failed = int(fail_match.group(1))
    err_match = re.search(r"(\d+)\s+error", summary_text)
    if err_match:
        errors = int(err_match.group(1))
    skip_match = re.search(r"(\d+)\s+skipped", summary_text)
    if skip_match:
        skipped = int(skip_match.group(1))

    total_failed = failed + errors
    return passed, total_failed, skipped

def ensure_sqlite_test_db():
    """Ensures deterministic SQLite test database is bootstrapped."""
    try:
        if BASE_DIR not in sys.path:
            sys.path.insert(0, BASE_DIR)
        from integration_omkar.scripts.bootstrap_test_db import bootstrap_sqlite
        bootstrap_sqlite()
    except Exception as e:
        print(f"[WARN] Failed to bootstrap SQLite test database: {e}")

def run_cmd(cmd: list[str], cwd: str, env: dict, suite_name: str) -> SuiteResult:
    res = SuiteResult(suite_name)
    start = time.time()
    
    is_pytest = "pytest" in cmd
    xml_path = None
    exec_cmd = list(cmd)
    if is_pytest:
        tmp_fd, xml_path = tempfile.mkstemp(prefix=f"junit_{suite_name}_", suffix=".xml")
        os.close(tmp_fd)
        exec_cmd.extend(["--junitxml", xml_path])

    print(f"\n[{suite_name.upper()}] Running: {' '.join(exec_cmd)} (cwd={os.path.relpath(cwd, BASE_DIR)})")
    
    proc = subprocess.run(exec_cmd, cwd=cwd, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    res.duration = time.time() - start
    res.exit_code = proc.returncode
    output = proc.stdout

    if is_pytest:
        p, f, s = 0, 0, 0
        if xml_path and os.path.exists(xml_path):
            p, f, s = parse_junit_xml(xml_path)
            try:
                os.remove(xml_path)
            except OSError:
                pass
        
        if p == 0 and f == 0 and s == 0:
            p, f, s = parse_pytest_output(output)

        res.passed = p
        res.failed = f
        res.skipped = s

        if proc.returncode != 0 and res.failed == 0:
            res.failed = 1
        if (res.passed + res.failed + res.skipped) == 0:
            res.failed = 1
            res.exit_code = 1
            res.message = "Zero tests collected"
    elif suite_name == "frontend":
        vitest_match = re.search(r"Tests\s+(\d+)\s+passed", output)
        if vitest_match:
            res.passed = int(vitest_match.group(1))
        elif proc.returncode == 0:
            res.passed = 1
        else:
            res.failed = 1
    elif suite_name == "flake8":
        if proc.returncode == 0:
            res.passed = 1
            res.message = "Clean syntax & import checks"
        else:
            res.failed = len([line for line in output.splitlines() if line.strip()])
            res.message = "Flake8 violations found"
    elif suite_name == "render-config":
        if proc.returncode == 0:
            res.passed = 1
            res.message = "render.yaml & compose valid"
        else:
            res.failed = 1
            res.message = "Configuration invalid"
    else:
        if proc.returncode == 0:
            res.passed = 1
        else:
            res.failed = 1

    status_str = "PASS" if res.exit_code == 0 and res.failed == 0 else "FAIL"
    print(f"[{suite_name.upper()}] Finished in {res.duration:.2f}s -> {status_str} ({res.passed} passed, {res.failed} failed, {res.skipped} skipped, {res.blocked} blocked)")
    if res.exit_code != 0 or res.failed > 0:
        print("--- Output excerpt on failure ---")
        lines = output.splitlines()
        print("\n".join(lines[-25:] if len(lines) > 25 else lines))
        print("---------------------------------")
    return res

